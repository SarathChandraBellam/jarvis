package com.jarvis.hud.model

/**
 * Phone data sources collected locally on-device.
 */
enum class DataSource(val label: String) {
  SMS("SMS"),
  NOTIFICATION("Notifications"),
  CALENDAR("Calendar"),
  CALL("Call Logs"),
  USAGE("Screen Time"),
}

/**
 * Organized intelligence categories rendered in Jarvis.
 */
enum class IntelCategory(val label: String) {
  FINANCE("Finance"),
  BILL("Bills"),
  DELIVERY("Deliveries"),
  TRAVEL("Travel"),
  ACTION("Action"),
  MESSAGE("Messages"),
  SCHEDULE("Schedule"),
  SYSTEM("System"),
}

/**
 * Urgency level for organized items and proactive alerts.
 */
enum class Priority(val label: String) {
  CRITICAL("CRITICAL"),
  HIGH("HIGH"),
  NORMAL("NORMAL"),
  LOW("LOW"),
}

/**
 * Lifecycle state for an actionable or tracked item.
 */
enum class ItemStatus {
  ACTIVE,
  DONE,
  DISMISSED,
}

/**
 * Primary bottom-dock sections.
 */
enum class HudTab(val label: String) {
  HUD("Today"),
  FINANCE("Subs"),
  INTEL("Inbox"),
  ASK("Ask"),
}

/** Subscription category for the Subscriptions & Renewals hub. */
enum class SubscriptionCategory(val label: String) {
  STREAMING("Streaming & Media"),
  SOFTWARE("Software & AI"),
  TELECOM("Telecom & Wi-Fi"),
  FITNESS("Fitness & Life"),
  UTILITIES("EMI & Utilities"),
}

/** Billing cadence for a tracked subscription. */
enum class BillingCadence(val label: String, val monthlyDivisor: Double) {
  WEEKLY("Weekly", 0.25),
  MONTHLY("Monthly", 1.0),
  QUARTERLY("Quarterly", 3.0),
  YEARLY("Yearly", 12.0),
}

/**
 * A recurring subscription or plan either auto-detected from SMS/notifications
 * or manually added by the user.
 */
data class TrackedSubscription(
  val id: String,
  val name: String,
  val amount: Double,
  val currency: String = "₹",
  val cadence: BillingCadence = BillingCadence.MONTHLY,
  val category: SubscriptionCategory = SubscriptionCategory.STREAMING,
  /** Next expected renewal date in ISO yyyy-MM-dd format. */
  val nextRenewalDate: String? = null,
  val isTrial: Boolean = false,
  val isPaused: Boolean = false,
  val isAutoDetected: Boolean = true,
  val sourceNote: String? = null,
) {
  val monthlyEquivalent: Double
    get() = if (isPaused) 0.0 else amount / cadence.monthlyDivisor
}

/**
 * User-created Day Planner task or quick reminder.
 */
data class PlannerReminder(
  val id: String,
  val title: String,
  /** Minute of day (0..1439) for placement on the 24h timeline. */
  val minutesOfDay: Int = 9 * 60,
  /** ISO date yyyy-MM-dd. */
  val dateKey: String,
  val isDone: Boolean = false,
  val notifyProactively: Boolean = true,
)

/** Category of proactive alert or nudge generated by Jarvis. */
enum class ProactiveKind(val label: String) {
  RENEWAL("Renewal"),
  BILL("Bill due"),
  BRIEFING("Briefing"),
  DELIVERY("Delivery"),
  CALL("Missed call"),
  FOCUS("Focus nudge"),
  REMINDER("Reminder"),
}

/**
 * Proactive notification / in-app nudge prepared for the user.
 */
data class ProactiveAlert(
  val id: String,
  val dedupKey: String,
  val kind: ProactiveKind,
  val title: String,
  val body: String,
  val priority: Priority = Priority.NORMAL,
  val timestamp: Long,
  val targetTab: HudTab? = null,
)

/**
 * Raw message, notification, or device event captured locally.
 */
data class RawEvent(
  val id: String,
  val source: DataSource,
  val sender: String,
  val title: String,
  val body: String,
  val timestamp: Long,
  val contentHash: String,
  val aiProcessed: Boolean = false,
)

/**
 * Structured intelligence item produced by OpenRouter AI or local deterministic parser.
 */
data class OrganizedItem(
  val id: String,
  val rawEventId: String?,
  val category: IntelCategory,
  val title: String,
  val summary: String,
  val amount: Double? = null,
  val currency: String = "₹",
  val isCredit: Boolean = false,
  val merchant: String? = null,
  val dueDate: String? = null,
  val priority: Priority = Priority.NORMAL,
  val status: ItemStatus = ItemStatus.ACTIVE,
  val timestamp: Long,
  val source: DataSource,
  /** Who sent the underlying event (SMS address or app name); identifies the delivery channel. */
  val sender: String? = null,
  /** Last 4 digits of the bank account / card involved, when the message names one. */
  val accountTail: String? = null,
  /** UPI / bank transaction reference number, when the message carries one. */
  val reference: String? = null,
)

/**
 * Daily tactical briefing.
 */
data class DailyBriefing(
  val dateKey: String,
  val headline: String,
  val summary: String,
  val highlights: List<String>,
  val modelUsed: String,
  val createdAt: Long,
)

/**
 * Message in the Ask Jarvis console.
 */
data class ChatMessage(
  val id: String,
  val isFromUser: Boolean,
  val content: String,
  val timestamp: Long,
  val modelUsed: String? = null,
)

/**
 * Calendar schedule event read from CalendarContract.
 */
data class CalendarEntry(
  val id: String,
  val title: String,
  val startTime: Long,
  val endTime: Long,
  val location: String?,
)

/**
 * Recent phone call entry read from CallLog.Calls.
 */
data class CallSummary(
  val id: String,
  val nameOrNumber: String,
  val callType: String,
  val durationSec: Long,
  val timestamp: Long,
)

/**
 * Per-app foreground screen time summary.
 */
data class AppUsageStat(
  val packageName: String,
  val appName: String,
  val foregroundMinutes: Long,
)

/**
 * Live device battery and storage telemetry.
 */
data class DeviceTelemetry(
  val batteryPercent: Int,
  val isCharging: Boolean,
  val freeStorageGb: Float,
  val totalStorageGb: Float,
)

/**
 * Metadata for an OpenRouter model returned by /api/v1/models.
 */
data class OpenRouterModelInfo(
  val id: String,
  val name: String,
  val contextLength: Int? = null,
  val isFree: Boolean = false,
)

/**
 * Snapshot of Android permissions and special access grants.
 */
data class PermissionStatus(
  val smsGranted: Boolean,
  val notificationAccessGranted: Boolean,
  val calendarGranted: Boolean,
  val callLogGranted: Boolean,
  val usageAccessGranted: Boolean,
  val notificationsPostGranted: Boolean = true,
) {
  val grantedCount: Int
    get() = listOf(
      smsGranted,
      notificationAccessGranted,
      calendarGranted,
      callLogGranted,
      usageAccessGranted,
    ).count { it }
}

/**
 * User configuration and persisted UI selections.
 */
data class JarvisSettings(
  val apiKey: String = "",
  val modelId: String = "google/gemini-2.5-flash",
  val userCallsign: String = "Sir",
  val voiceEnabled: Boolean = true,
  val redactSensitiveData: Boolean = true,
  val enabledSources: Set<DataSource> = DataSource.entries.toSet(),
  val aiShareSources: Set<DataSource> = DataSource.entries.toSet(),
  /** False until the user finishes (or skips) the welcome screen. */
  val onboardingDone: Boolean = false,
  /** Legacy budget field kept for settings compatibility; unused in Subscriptions-only UI. */
  val monthlyBudget: Double = 0.0,
  /** Persisted UI selections across restarts & app version updates. */
  val selectedTabName: String = HudTab.HUD.name,
  val subsViewIndex: Int = 0,
  val inboxCategoryName: String? = null,
  val inboxShowCompleted: Boolean = false,
  /** Proactive notifications & focus preferences. */
  val proactiveNotificationsEnabled: Boolean = true,
  val renewalLeadDays: Int = 3,
  val morningBriefingHour: Int = 8,
  val dailyFocusGoalMinutes: Int = 120,
)

/**
 * Result of testing the user's OpenRouter API key and model uplink.
 */
data class ConnectionTestResult(
  val success: Boolean,
  val message: String,
  val latencyMs: Long = 0L,
)

/**
 * Single immutable UI state driving the entire Jarvis experience.
 */
data class JarvisUiState(
  val selectedTab: HudTab = HudTab.HUD,
  val showSettings: Boolean = false,
  val isSyncing: Boolean = false,
  val syncStatusLine: String = "Ready",
  val isSpeaking: Boolean = false,
  val isAskingAi: Boolean = false,
  val settings: JarvisSettings = JarvisSettings(),
  val permissions: PermissionStatus = PermissionStatus(
    smsGranted = false,
    notificationAccessGranted = false,
    calendarGranted = false,
    callLogGranted = false,
    usageAccessGranted = false,
  ),
  val telemetry: DeviceTelemetry = DeviceTelemetry(
    batteryPercent = 88,
    isCharging = false,
    freeStorageGb = 64.5f,
    totalStorageGb = 128.0f,
  ),
  val briefing: DailyBriefing? = null,
  val items: List<OrganizedItem> = emptyList(),
  val subscriptions: List<TrackedSubscription> = emptyList(),
  val reminders: List<PlannerReminder> = emptyList(),
  val proactiveAlerts: List<ProactiveAlert> = emptyList(),
  val calendarEntries: List<CalendarEntry> = emptyList(),
  val recentCalls: List<CallSummary> = emptyList(),
  val appUsageStats: List<AppUsageStat> = emptyList(),
  val chatMessages: List<ChatMessage> = emptyList(),
  val availableModels: List<OpenRouterModelInfo> = emptyList(),
  val isLoadingModels: Boolean = false,
  val connectionTestResult: ConnectionTestResult? = null,
  val lastError: String? = null,
  /** Item shown in the details sheet, if any. */
  val openItemId: String? = null,
) {
  val openItem: OrganizedItem? get() = openItemId?.let { id -> items.firstOrNull { it.id == id } }
}

